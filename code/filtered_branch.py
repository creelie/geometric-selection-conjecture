"""Filtered bundles on X_pi / Gamma built from the five Gamma-data (Section 16.5).

A filtered Gamma-bundle of a datum is a Gamma-equivariant bundle E on X_pi with a filtration
0 = F_0 < F_1 < ... < F_5 = E by Gamma-subbundles whose quotients F_j / F_{j-1} are the line bundles L_a of the
datum, in some order sigma (a flag order of E).  Every bundle of Sections 16.3 and 16.4 is one.

Swap lemma (Lemma 16.20): if a = sigma(j-1), b = sigma(j) and H^1(L_a L_b^{-1}) = 0, then F_j / F_{j-2} splits and E
also has the flag order with a and b exchanged.  So E has every linear extension of the partial order P_sigma
generated by the pairs (a, b), a before b in sigma, with H^1(L_a L_b^{-1}) != 0 (the links), and for every down-set
S of P_sigma a Gamma-subbundle E_S filtered by the L_a, a in S, with E / E_S filtered by the others.

Selection rule (Lemma 16.14(b),(c) for E_S): give a class of H^1(wedge^i E) the level m when it lies in the image of
H^1(Im(wedge^m E_S x wedge^(i-m) E)); a cubic coupling vanishes when the levels add up to more than |S|, and a class
has level at least m when every piece L_I, |I| = i, with |I & S| < m has H^1 = 0.  The rank of a Yukawa matrix is at
most the term rank of the pattern of allowed (level, level) blocks.

This program computes the links and pieces on X_pi exactly, checks the facts used in the hand proof of
Theorem 16.21, and recomputes its conclusions for all 120 orders sigma and every down-set, with character-blind
multiplicities (valid for every equivariant structure and Wilson line).

Output: filtered_branch_results.json.
"""
import json, os, sys
from collections import Counter
from itertools import combinations, permutations

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gamma_branch import DATA, add, coh, neg, term_rank

HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = ["fixed", "class 6", "class 8", "class 9", "class 10"]


def closure(rel):
    rel = set(rel)
    while True:
        new = {(a, d) for a, b in rel for c, d in rel if b == c} - rel
        if not new:
            return rel
        rel |= new


def down_sets(P):
    return [set(S) for r in range(1, 5) for S in combinations(range(5), r)
            if all(a in S for (a, b) in P if b in S)]


def level_bounds(n, h1pair, h2pair, S):
    """Term-rank bounds (Y_u, Y_d) for the subbundle E_S; Y_e has the same bound as Y_d (same multiplicities)."""
    lev = {a: int(a in S) for a in range(5)}
    Q = Counter()
    for a in range(5):
        if n[a]:
            Q[lev[a]] += n[a]
    D = Counter()
    for (a, b), m in h1pair.items():
        D[lev[a] + lev[b]] += m
    W = len(S)
    hu = [W - lev[a] - lev[b] for (a, b) in h2pair]          # level of the piece L_{ {a,b}^c } of wedge^3
    hd = [lev[a] + lev[b] for (a, b) in h1pair]
    ru = term_rank(dict(Q), dict(Q), {(p, q) for p in Q for q in Q if p + q + min(hu) <= W}) if hu else 0
    rd = term_rank(dict(Q), dict(D), {(p, q) for p in Q for q in D if p + q + min(hd) <= W}) if hd else 0
    return ru, rd


def main():
    passed = failed = 0

    def check(ok, what):
        nonlocal passed, failed
        if ok:
            passed += 1
        else:
            failed += 1
            print("FAILED:", what)

    expect_links = {
        "fixed": {(2, 1): 12, (2, 3): 20, (2, 4): 12, (2, 5): 2, (5, 1): 12, (5, 2): 2, (5, 3): 4},
        "class 6": {(2, 5): 3, (3, 1): 4, (3, 2): 16, (4, 1): 12, (4, 3): 12, (5, 2): 3, (5, 4): 12},
        "class 8": {(1, 2): 4, (2, 4): 3, (2, 5): 3, (3, 2): 16, (4, 1): 8, (4, 2): 3, (4, 5): 3, (5, 1): 8,
                    (5, 2): 3, (5, 4): 3},
        "class 9": {(2, 1): 4, (3, 2): 12, (4, 2): 12, (5, 1): 8, (5, 2): 28, (5, 3): 36, (5, 4): 36},
        "class 10": {(2, 1): 4, (3, 2): 12, (4, 2): 12, (5, 1): 12, (5, 2): 24, (5, 3): 36, (5, 4): 32}}
    expect_pieces = {
        "fixed": ({2: 8, 5: 4}, {(2, 4): (4, 0), (2, 5): (3, 3), (4, 5): (8, 0)}),
        "class 6": ({3: 4, 4: 4, 5: 4}, {(1, 2): (4, 0), (1, 5): (4, 0), (2, 4): (4, 0), (2, 5): (3, 3)}),
        "class 8": ({3: 4, 4: 4, 5: 4}, {(1, 2): (4, 0), (1, 3): (8, 0), (2, 4): (3, 3), (2, 5): (3, 3), (4, 5): (3, 3)}),
        "class 9": ({5: 12}, {(1, 5): (12, 0), (3, 4): (3, 3)}),
        "class 10": ({5: 12}, {(1, 5): (8, 0), (2, 4): (4, 0), (2, 5): (3, 3)})}
    # the conclusions of Theorem 16.21 over all orders, as (max rank Y_u, max rank Y_d) and the forbidden pairs
    expect_max = {"fixed": (3, 0), "class 6": (3, 3), "class 8": (2, 3), "class 9": (0, 0), "class 10": (0, 0)}
    results = {}
    for name, g, K in DATA:
        if name not in NAMES:
            continue
        rec = {}
        links = {(a + 1, b + 1): coh(add(K[a], neg(K[b])))[0][1] for a in range(5) for b in range(5)
                 if a != b and coh(add(K[a], neg(K[b])))[0][1]}
        check(links == expect_links[name], f"{name}: the pairs with H^1(L_a L_b^-1) != 0 on X_pi")
        one = {a + 1: coh(K[a])[0] for a in range(5)}
        two = {(a + 1, b + 1): coh(add(K[a], K[b]))[0] for a, b in combinations(range(5), 2)}
        check(all(d[0] == d[2] == d[3] == 0 for d in one.values()), f"{name}: every L_a has cohomology only in degree one")
        check(all(d[0] == d[3] == 0 for d in two.values()), f"{name}: every L_a L_b has H^0 = H^3 = 0")
        got = ({a: d[1] for a, d in one.items() if d[1]}, {k: (d[1], d[2]) for k, d in two.items() if any(d)})
        check(got == expect_pieces[name], f"{name}: the pieces with nonzero cohomology")
        n = [one[a][1] // 4 for a in range(1, 6)]
        check(sum(n) == 3 and all(one[a][1] % 4 == 0 for a in one), f"{name}: three families, n = {n}")
        h1pair = {(a - 1, b - 1): d[1] for (a, b), d in two.items() if d[1]}
        h2pair = [(a - 1, b - 1) for (a, b), d in two.items() if d[2]]
        link0 = {(a - 1, b - 1) for (a, b) in links}
        worst = Counter()
        rows = []
        for sig in permutations(range(5)):
            P = closure({(a, b) for a, b in link0 if sig.index(a) < sig.index(b)})
            bs = [level_bounds(n, h1pair, h2pair, S) for S in down_sets(P)]
            b = (min(x[0] for x in bs), min(x[1] for x in bs))
            worst[b] += 1
            rows.append(dict(order=[x + 1 for x in sig], bounds=list(b)))
            check(not (b[0] >= 3 and b[1] >= 3), f"{name} order {[x + 1 for x in sig]}: Y_u and Y_d not both of rank 3")
        mx = (max(b[0] for b in worst), max(b[1] for b in worst))
        check(mx == expect_max[name], f"{name}: the largest bounds over all orders are {mx}")
        rec["links"] = {f"L{a}->L{b}": m for (a, b), m in links.items()}
        rec["families"] = n
        rec["bound_counts"] = {f"{u},{d}": c for (u, d), c in sorted(worst.items())}
        rec["orders"] = rows
        results[name] = rec

        # ---- the facts used in the hand proofs
        inc = {b: {a for (a, c) in links if c == b} for b in range(1, 6)}
        out = {a: {c for (x, c) in links if x == a} for a in range(1, 6)}
        if name == "fixed":
            check(not out[1] and not out[3], "fixed: no link leaves L_1 or L_3, so {2,4,5} is a down-set of every order")
            check(set(got[0]) | {x for k in got[1] for x in k} <= {2, 4, 5}, "fixed: every nonzero piece lies in {2,4,5}")
            check(level_bounds(n, h1pair, h2pair, {1, 3, 4})[1] == 0, "fixed: S = {2,4,5} gives Y_d = Y_e = 0")
        if name == "class 6":
            check(inc[3] == {4} and inc[4] == {5} and inc[5] == {2}, "class 6: links into L3, L4, L5 come only from L4, L5, L2")
            check(level_bounds(n, h1pair, h2pair, {2})[0] <= 2 and level_bounds(n, h1pair, h2pair, {3})[0] <= 2,
                  "class 6: S = {3} or {4} gives rank Y_u <= 2")
            check(level_bounds(n, h1pair, h2pair, {1, 4})[1] <= 2, "class 6: S = {2,5} gives rank Y_d, Y_e <= 2")
            check(level_bounds(n, h1pair, h2pair, {2, 3, 4})[0] == 0, "class 6: S = {3,4,5} gives Y_u = 0")
        if name == "class 8":
            check(not inc[3], "class 8: no link enters L_3, so {3} is a down-set of every order")
            check(all(3 not in k for k in got[1] if got[1][k][1]), "class 8: every pair with H^2 != 0 avoids L_3")
            check(level_bounds(n, h1pair, h2pair, {2})[0] <= 2, "class 8: S = {3} gives rank Y_u <= 2")
        if name in ("class 9", "class 10"):
            check(not inc[5] and inc[4] == {5}, f"{name}: no link enters L_5 and only L_5 -> L_4 enters L_4")
            check(level_bounds(n, h1pair, h2pair, {3, 4}) == (0, 0), f"{name}: S = {{4,5}} gives Y_u = Y_d = Y_e = 0")
        print(name, "families", n, "links", rec["links"], "bounds", rec["bound_counts"])

    json.dump(results, open(os.path.join(HERE, "filtered_branch_results.json"), "w"), indent=1)
    print(f"{passed} checks passed, {failed} failed")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
